// Package completion renders shell completion scripts from the doc
// structs. Static parts (subcommands, flags, fixed values) are written into
// the script; names that depend on state come from `hm __complete`.
package completion

import (
	"fmt"
	"strings"

	"github.com/catgrep/nixos-config/tools/hm/internal/doc"
)

// Shells returns the supported shells.
func Shells() []string {
	return []string{"zsh", "bash", "fish"}
}

// Script returns the completion script for shell.
func Script(shell string) (string, error) {
	switch shell {
	case "zsh":
		return Zsh(), nil
	case "bash":
		return Bash(), nil
	case "fish":
		return Fish(), nil
	}
	return "", fmt.Errorf("unknown shell %q; expected zsh, bash or fish", shell)
}

func visible() []doc.Command {
	var out []doc.Command
	for _, c := range doc.Commands() {
		if !c.Hidden {
			out = append(out, c)
		}
	}
	return out
}

func zshQuote(s string) string {
	return strings.NewReplacer(`'`, `'\''`, `[`, `\[`, `]`, `\]`, `:`, `\:`).Replace(s)
}

// Zsh renders the _hm completion function.
func Zsh() string {
	var b strings.Builder
	b.WriteString("#compdef hm\n# Generated by hm completion zsh; do not edit.\n\n")
	b.WriteString("_hm_dynamic() {\n  local -a candidates\n  candidates=(${(f)\"$(hm __complete \"${words[@]:1}\" 2>/dev/null)\"})\n  (( ${#candidates} )) && _describe 'value' candidates\n}\n\n")
	b.WriteString("_hm() {\n  local -a commands globals\n  commands=(\n")
	for _, c := range visible() {
		fmt.Fprintf(&b, "    '%s:%s'\n", c.Name, zshQuote(c.Summary))
	}
	b.WriteString("  )\n  globals=(\n")
	for _, f := range doc.GlobalFlags() {
		b.WriteString("    " + zshFlagSpec(f) + "\n")
	}
	b.WriteString("  )\n  _arguments -C $globals '1:command:->command' '*::arg:->args' && return\n")
	b.WriteString("  case $state in\n    command) _describe 'command' commands ;;\n    args)\n      case $words[1] in\n")
	for _, c := range visible() {
		fmt.Fprintf(&b, "        %s)\n          _arguments $globals", c.Name)
		for _, f := range c.Flags {
			b.WriteString(" \\\n            " + zshFlagSpec(f))
		}
		if c.Complete != doc.CompleteNone || c.Args != "" {
			b.WriteString(" \\\n            '*:argument:_hm_dynamic'")
		}
		b.WriteString("\n          ;;\n")
	}
	b.WriteString("      esac\n      ;;\n  esac\n}\n\n_hm \"$@\"\n")
	return b.String()
}

func zshFlagSpec(f doc.Flag) string {
	help := zshQuote(f.Help)
	if len(help) > 60 {
		help = help[:57] + "..."
	}
	if f.Arg == "" {
		return fmt.Sprintf("'--%s[%s]'", f.Name, help)
	}
	action := "_hm_dynamic"
	switch {
	case len(f.Values) > 0:
		action = "(" + strings.Join(f.Values, " ") + ")"
	case f.Arg == "PATH":
		action = "_files"
	}
	return fmt.Sprintf("'--%s=[%s]:%s:%s' '--%s[%s]:%s:%s'", f.Name, help, strings.ToLower(f.Arg), action, f.Name, help, strings.ToLower(f.Arg), action)
}

// Bash renders the bash completion function.
func Bash() string {
	var b strings.Builder
	b.WriteString("# Generated by hm completion bash; do not edit.\n\n_hm() {\n")
	b.WriteString("  local cur prev words cword\n  if declare -F _init_completion >/dev/null 2>&1; then\n    _init_completion || return\n  else\n    cur=${COMP_WORDS[COMP_CWORD]}\n    prev=${COMP_WORDS[COMP_CWORD-1]}\n    words=(\"${COMP_WORDS[@]}\")\n    cword=$COMP_CWORD\n  fi\n")
	b.WriteString("  local globals='")
	for _, f := range doc.GlobalFlags() {
		b.WriteString("--" + f.Name + " ")
	}
	b.WriteString("'\n  local cmd=\"\" i\n  for ((i = 1; i < cword; i++)); do\n    case ${words[i]} in\n      --flake) ((i++)) ;;\n      -*) ;;\n      *) cmd=${words[i]}; break ;;\n    esac\n  done\n")
	b.WriteString("  if [[ $prev == --flake || $prev == --generation ]]; then\n    compopt -o filenames 2>/dev/null\n    COMPREPLY=($(compgen -f -- \"$cur\"))\n    return\n  fi\n")
	b.WriteString("  if [[ -z $cmd ]]; then\n    COMPREPLY=($(compgen -W '")
	for _, c := range visible() {
		b.WriteString(c.Name + " ")
	}
	b.WriteString("'\"$globals\" -- \"$cur\"))\n    return\n  fi\n  case $cmd in\n")
	for _, c := range visible() {
		fmt.Fprintf(&b, "    %s)\n      if [[ $cur == -* ]]; then\n        COMPREPLY=($(compgen -W '", c.Name)
		for _, f := range c.Flags {
			b.WriteString("--" + f.Name + " ")
		}
		b.WriteString("'\"$globals\" -- \"$cur\"))\n        return\n      fi\n")
		for _, f := range c.Flags {
			if len(f.Values) > 0 {
				fmt.Fprintf(&b, "      if [[ $prev == --%s ]]; then\n        COMPREPLY=($(compgen -W '%s' -- \"$cur\"))\n        return\n      fi\n", f.Name, strings.Join(f.Values, " "))
			}
		}
		b.WriteString("      ;;\n")
	}
	b.WriteString("  esac\n  COMPREPLY=($(compgen -W \"$(hm __complete \"${words[@]:1:cword}\" 2>/dev/null)\" -- \"$cur\"))\n}\n\ncomplete -F _hm hm\n")
	return b.String()
}

func fishQuote(s string) string {
	return strings.ReplaceAll(s, "'", `\'`)
}

// Fish renders fish completions.
func Fish() string {
	var b strings.Builder
	b.WriteString("# Generated by hm completion fish; do not edit.\n\n")
	var names []string
	for _, c := range visible() {
		names = append(names, c.Name)
	}
	seen := "__fish_seen_subcommand_from " + strings.Join(names, " ")
	for _, f := range doc.GlobalFlags() {
		fmt.Fprintf(&b, "complete -c hm -l %s -d '%s'", f.Name, fishQuote(f.Help))
		if f.Arg == "PATH" {
			b.WriteString(" -r -F")
		}
		b.WriteByte('\n')
	}
	for _, c := range visible() {
		fmt.Fprintf(&b, "complete -c hm -n 'not %s' -a %s -d '%s'\n", seen, c.Name, fishQuote(c.Summary))
	}
	for _, c := range visible() {
		for _, f := range c.Flags {
			fmt.Fprintf(&b, "complete -c hm -n '__fish_seen_subcommand_from %s' -l %s -d '%s'", c.Name, f.Name, fishQuote(shorten(f.Help)))
			switch {
			case len(f.Values) > 0:
				fmt.Fprintf(&b, " -x -a '%s'", strings.Join(f.Values, " "))
			case f.Arg == "PATH":
				b.WriteString(" -r -F")
			case f.Arg != "":
				b.WriteString(" -x")
			}
			b.WriteByte('\n')
		}
		if c.Complete != doc.CompleteNone || c.Args != "" {
			fmt.Fprintf(&b, "complete -c hm -n '__fish_seen_subcommand_from %s' -f -a '(hm __complete (commandline -opc)[2..] (commandline -ct) 2>/dev/null)'\n", c.Name)
		}
	}
	return b.String()
}

func shorten(s string) string {
	if len(s) > 70 {
		return s[:67] + "..."
	}
	return s
}
